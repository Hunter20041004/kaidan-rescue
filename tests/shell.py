# Shell: python3 tests/shell.py <abs html> [screenshot dir] — start screen, settings that stick, credits, no debug numbers on screen
import sys,json
from playwright.sync_api import sync_playwright
URL='file://'+sys.argv[1];OUT=sys.argv[2] if len(sys.argv)>2 else None;res=[]
def check(n,ok,d=''):res.append((n,bool(ok),d))
with sync_playwright() as p:
  b=p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
  for name,vp,touch in [('desk',{'width':1280,'height':800},False),('mob',{'width':375,'height':812},True)]:
    pg=b.new_page(viewport=vp,has_touch=touch,is_mobile=touch);errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(URL);pg.wait_for_timeout(700);pg.evaluate("localStorage.clear()");pg.reload();pg.wait_for_timeout(1200)
    vis=lambda s:pg.evaluate(f"!document.querySelector('{s}').hidden")
    pg.evaluate("document.querySelector('#boot').hidden=false");pg.wait_for_timeout(1800)
    if OUT:pg.screenshot(path=f'{OUT}/{name}-boot.png')
    (pg.tap if touch else pg.click)('#boot');pg.wait_for_timeout(300)
    check(f'{name} 開始畫面按一下就進標題、聲音啟動',not vis('#boot') and vis('#title') and pg.evaluate("!!SND.ac"))
    pg.click('#m-settings');pg.wait_for_timeout(500)
    if OUT:pg.screenshot(path=f'{OUT}/{name}-settings.png')
    pg.evaluate("(()=>{const el=document.querySelector('#v-music');el.value=20;el.dispatchEvent(new Event('input'))})()")
    g=pg.evaluate("[SND.mus.gain.value,SND.fx.gain.value,SND.out.gain.value]")
    check(f'{name} 配樂音量拉到 20 → 配樂通道 0.2',abs(g[0]-.2)<1e-6,g)
    if not touch:
      pg.focus('#v-master');pg.keyboard.press('ArrowLeft');pg.wait_for_timeout(100)
      check(f'{name} 方向鍵調得動滑桿',pg.evaluate("SND.vol.master")==75,pg.evaluate("SND.vol.master"))
      pg.keyboard.press('Tab');check(f'{name} Tab 能離開滑桿',pg.evaluate("document.activeElement.id")=='v-music',pg.evaluate("document.activeElement.id"))
    pg.keyboard.press('Escape');pg.wait_for_timeout(200)
    check(f'{name} Esc 關掉設定',not vis('#settings'))
    pg.reload();pg.wait_for_timeout(900)
    check(f'{name} 重新整理後音量設定還在',pg.evaluate("SND.vol.music")==20,pg.evaluate("SND.vol"))
    pg.click('#m-credits');pg.wait_for_timeout(500)
    if OUT:pg.screenshot(path=f'{OUT}/{name}-credits.png')
    check(f'{name} 製作名單列出 CC0 音效與字型授權','CC0' in pg.inner_text('#credits') and 'Open Font' in pg.inner_text('#credits'))
    pg.keyboard.press('Escape');pg.wait_for_timeout(200)
    check(f'{name} 關掉製作名單，焦點回到按鈕',pg.evaluate("document.activeElement.id")=='m-credits',pg.evaluate("document.activeElement.id"))
    if not touch:
      pg.focus('#m-start');pg.keyboard.down('Enter');pg.wait_for_timeout(100)
      for i in range(12):pg.keyboard.down('Enter');pg.wait_for_timeout(60)
      pg.keyboard.up('Enter');pg.wait_for_timeout(300)
      check(f'{name} 按住 Enter 不會跳過開場直接開始',pg.evaluate("!KT.G||KT.G.menuMode") and vis('#intro'),[vis('#intro'),vis('#nightcard')])
      pg.keyboard.press('Escape');pg.wait_for_timeout(200);pg.evaluate("KT.toTitle()");pg.evaluate("localStorage.removeItem('kaidan-run')");pg.wait_for_timeout(200)
    pg.click('#m-start');pg.wait_for_timeout(1200)
    if OUT:pg.screenshot(path=f'{OUT}/{name}-intro.png')
    pg.keyboard.press('Escape');pg.wait_for_timeout(300);pg.click('#ncgo');pg.wait_for_timeout(300)
    pg.evaluate("KT.setPause(true)");pg.wait_for_timeout(300)
    check(f'{name} 暫停選單有設定，聲音／特寫收進設定裡',vis('#psettings') and not pg.evaluate("document.querySelector('#pause').contains(document.querySelector('#closeup'))"))
    pg.click('#psettings');pg.wait_for_timeout(300);pg.keyboard.press('Escape');pg.wait_for_timeout(200)
    check(f'{name} 從暫停打開設定再關掉，回到暫停',vis('#pause') and not vis('#settings'))
    pg.evaluate("KT.setPause(false);KT.toTitle()");pg.click('#m-quick');pg.wait_for_timeout(300)
    pg.evaluate("(()=>{const G=KT.G;KT.manual=true;G.scare={type:'tiger',t:0};G.player.dead=true;KT.endGame('dead')})()");pg.wait_for_timeout(1500)
    txt=pg.inner_text('#deathwho')
    check(f'{name} 單夜死亡卡沒有除錯用的夜編號','#' not in txt,txt)
    check(f'{name} 沒有頁面錯誤',not errs and not pg.evaluate('KT.err||null'),errs)
    pg.close()
  for n,ok,d in res:print('PASS' if ok else 'FAIL',n,'—',json.dumps(d,ensure_ascii=False)[:160] if d!='' else '')
  print('PASS:',sum(1 for r in res if r[1]),'FAIL:',sum(1 for r in res if not r[1]))
