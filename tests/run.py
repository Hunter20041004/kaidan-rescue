  pg.click('#m-start');pg.wait_for_timeout(300)
  check('新的一輪先播開場（老村長、停電、送月曆的貨車）',vis('#intro') and '老村長' in pg.inner_text('#introline'),pg.inner_text('#introline'))
  pg.keyboard.press('Space');pg.wait_for_timeout(150);l2=pg.inner_text('#introline')
