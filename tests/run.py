# 七夜 flow: python3 tests/run.py <abs html>
# Drives the run through the real screens (buttons and keys) and checks what carries from night to night.
import sys,json
from playwright.sync_api import sync_playwright
URL='file://'+sys.argv[1];res=[]
def check(name,ok,detail=''):res.append((name,bool(ok),detail))
with sync_playwright() as p:
  b=p.chromium.launch();pg=b.new_page(viewport={'width':1280,'height':800});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
