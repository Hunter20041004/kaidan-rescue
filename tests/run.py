  vis=lambda s:pg.evaluate(f"!document.querySelector('{s}').hidden")
  def end_night(kind,lose=0):
    # finish the current night: kind 'escape' saves everyone still alive except `lose` villagers, who die; 'dead' kills the player
    pg.evaluate("""([kind,lose])=>{KT.manual=true;const G=KT.G,sv=G.humans.filter(h=>!h.isPlayer);sv.slice(0,lose).forEach(h=>{h.dead=true;h.killer='虎姑婆'});
      if(kind==='escape'){sv.slice(lose).forEach(h=>{h.saved=true;G.saved++});KT.endGame('escape')}else{G.scare={type:'tiger',t:0};KT.endGame('dead')}}""",[kind,lose])
    pg.wait_for_timeout(1300)
