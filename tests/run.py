  pg.click('#m-start');pg.wait_for_timeout(300)
  check('入夜先回到選祝福',vis('#bless'))
  bag=pg.evaluate("(()=>{const r=KT.RUN;r.offer=['bag','lung','legs'];const before=Object.values(r.inv).reduce((a,b)=>a+b,0);KT.pickBless('bag');return [before,Object.values(KT.RUN.inv).reduce((a,b)=>a+b,0)]})()")
  check('多一袋選到就補兩樣',bag[1]==bag[0]+2,bag)
  kids=pg.evaluate("(()=>{const all=NAMES.concat(MORE_NAMES);try{KT.startGame(5,'village',{cfg:KT.NIGHTS[6],exclude:all.filter(n=>n.kind==='child').map(n=>n.name)});return KT.G.humans.length}catch(e){return String(e)}})()")
