  pg.keyboard.press('Escape');pg.wait_for_timeout(300)
  check('入夜先看到夜卡',vis('#nightcard') and pg.inner_text('#ncname')=='頭一夜',pg.inner_text('#ncname'))
  check('夜卡顯示三個替身',pg.evaluate("document.querySelectorAll('#nclives .doll:not(.burnt)').length")==3)
  pg.keyboard.press('Enter');pg.wait_for_timeout(300);n1=night()
  check('第一夜：4 分鐘、4 人、2 隻怪、1 個規矩',n1['run'] and n1['len']==240 and len(n1['surv'])==4 and n1['sched']==2 and len(n1['apps'])==1,n1)
  check('HUD 顯示夜名',pg.inner_text('#dawn').startswith('頭一夜'),pg.inner_text('#dawn'))
  # win night 1, losing one villager
  end_night('escape',1)
  check('報紙按鈕是往下一夜',vis('#end') and '下一夜' in pg.inner_text('#again') and pg.evaluate("document.querySelector('#replay').hidden"),pg.inner_text('#again'))
  check('報紙寫出停電第幾夜',('停電的頭一夜' in pg.inner_text('#article')),pg.inner_text('#article')[:60])
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
  check('天亮後選祝福：三張卡',vis('#bless') and pg.evaluate("document.querySelectorAll('#blcards .bcard').length")==3)
  offer=pg.evaluate("KT.RUN.offer");pg.keyboard.press('Digit1');pg.wait_for_timeout(300)
  r=pg.evaluate("({bless:KT.RUN.bless,night:KT.RUN.night,calls:KT.RUN.calls,gifts:KT.RUN.gifts,inv:KT.RUN.inv})")
  check('按 1 拿到第一張祝福',r['bless']==[offer[0]] and vis('#nightcard') and pg.inner_text('#ncname')=='第二夜',r)
  check('救到的人送謝禮（3 人 → 3 樣）',len(r['gifts'])>=3 and '送你' in pg.inner_text('#ncbody'),r['gifts'])
  check('沒回來的人寫在夜卡上',len(r['calls'])==1 and r['calls'][0] in pg.inner_text('#ncbody'),r['calls'])
  # persistence: reload on the night card, continue from the title
  pg.reload();pg.wait_for_timeout(800)
  check('重新整理後標題顯示繼續第二夜',('繼續第二夜' in pg.inner_text('#m-start-sub')) and vis('#m-new'),pg.inner_text('#m-start-sub'))
  pg.click('#m-start');pg.wait_for_timeout(300);pg.click('#ncgo');pg.wait_for_timeout(300);n2=night()
  check('第二夜：沒有第一夜的人',not set(n2['surv'])&set(n1['surv']),[n1['surv'],n2['surv']])
  check('第二夜：失去的人會叫你（叫名字必出、怪更快）','voice' in n2['apps'] and n2['heatK']>pg.evaluate("KT.NIGHTS[1].heat"),[n2['apps'],n2['heatK']])
  check('第二夜：帶著謝禮的道具',sum(n2['inv'].values())>=sum(n1['inv'].values())+3,[n1['inv'],n2['inv']])
  check('第二夜：祝福生效',(offer[0]!='lung' or n2['breath']==7) and (offer[0]!='charm' or n2['charm']==1),[offer[0],n2['breath'],n2['charm']])
  # voice apparition uses the lost name
  pg.evaluate("(()=>{const G=KT.G;G.schedule=[];G.apps=[];KT.startApparition('voice');KT.UI.closeMeet();KT.step(120)})()")
  said=pg.evaluate("KT.G.bubbles.map(b=>b.text).join('|')")
  check('叫名字的是昨夜沒回來的人',r['calls'][0] in said,said)
  # death burns a stand-in and replays the same night
  pg.evaluate("KT.G.apparition=null");end_night('dead')
  check('死亡卡：紙人替死、剩 2 個',vis('#death') and '剩 2' in pg.inner_text('#deathwho') and '再來一次第二夜' in pg.inner_text('#dretry'),[pg.inner_text('#deathwho'),pg.inner_text('#dretry')])
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300);n2b=night()
  check('重來的是同一夜、同一批人',n2b['n']==1 and n2b['seed']==n2['seed'] and n2b['surv']==n2['surv'],[n2b['n'],n2b['surv']])
  check('遊戲中 R 不會偷偷重來',pg.evaluate("(()=>{const s=KT.G.seed,t=KT.G;window.dispatchEvent(new KeyboardEvent('keydown',{code:'KeyR'}));return KT.G===t})()"))
  check('暫停選單沒有「重玩這一夜」',pg.evaluate("KT.setPause(true),document.querySelector('#restart').hidden"));pg.evaluate("KT.setPause(false)")
  # three more deaths: the third burns the last stand-in, the fourth ends the run
  for i in range(2):end_night('dead');pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
  end_night('dead')
  check('替身燒完：死亡卡寫七夜到此為止',('到此為止' in pg.inner_text('#dretry')) and ('燒完' in pg.inner_text('#deathwho')),pg.inner_text('#deathwho'))
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
  check('七夜錄：失敗結局、列出七夜',vis('#runend') and '替身燒完' in pg.inner_text('#rehead') and pg.evaluate("document.querySelectorAll('#rerows div').length")==7,pg.inner_text('#rehead'))
  check('七夜錄寫下沒回來的人',r['calls'][0] in pg.inner_text('#relost'))
  check('結束後存檔清掉',pg.evaluate("localStorage.getItem('kaidan-run')")=='null')
  # a full run to 頭七
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300);pg.keyboard.press('Escape');pg.wait_for_timeout(200);lens=[];mods=[]
  for i in range(7):
    pg.keyboard.press('Enter');pg.wait_for_timeout(250);nn=night();lens.append((nn['len'],len(nn['surv']),nn['sched']));mods.append(nn['mod'])
    end_night('escape');pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
    if i<6:pg.keyboard.press('Digit2');pg.wait_for_timeout(250)
  check('七夜一路變長、變多',lens==[(240,4,2),(255,4,2),(270,5,3),(285,5,3),(300,5,3),(315,6,4),(330,6,4)],lens)
  check('第七夜固定是頭七（不是鬼門開：那是農曆七月），前後兩夜狀況不重複',mods[6]=='touqi' and all(mods[i]!=mods[i+1] for i in range(5)),mods)
  check('走完七夜：全員獲救的結局',vis('#runend') and '一個人都沒少' in pg.inner_text('#rehead'),pg.inner_text('#rehead'))
  check('七夜祝福拿了六個不重複',pg.evaluate("JSON.parse(localStorage.getItem('kaidan-bestrun')).nights")==7)
  check('試玩紀錄有每夜資料',pg.evaluate("KT.playsText()").count('"kind": "night"')+pg.evaluate("KT.playsText()").count('"kind":"night"')>=11)
  pg.keyboard.press('Escape');pg.wait_for_timeout(300)
  check('回標題顯示最好紀錄與試玩紀錄按鈕',('走完七夜' in pg.inner_text('#best')) and vis('#m-plays'),pg.inner_text('#best'))
  # review fixes (2026-10-28)
  pg.evaluate("localStorage.removeItem('kaidan-run')");pg.click('#m-start');pg.wait_for_timeout(300);pg.keyboard.press('Escape');pg.wait_for_timeout(200);pg.click('#ncgo');pg.wait_for_timeout(300)
  check('平安符…等：七夜開始時寫入「進行中」',pg.evaluate("JSON.parse(localStorage.getItem('kaidan-run')).live")==0)
  pg.evaluate("KT.setPause(true)");check('暫停的回標題寫明會燒替身','燒' in pg.inner_text('#totitle'),pg.inner_text('#totitle'))
  pg.click('#totitle');pg.wait_for_timeout(400)
  check('半夜回標題要燒一個替身',('替身剩 2' in pg.inner_text('#m-start-sub')),pg.inner_text('#m-start-sub'))
  pg.click('#m-start');pg.wait_for_timeout(300);pg.click('#ncgo');pg.wait_for_timeout(300)
  pg.evaluate("(()=>{const G=KT.G;G.scare={type:'tiger',t:0};G.player.dead=true;KT.endGame('dead')})()");pg.wait_for_timeout(300);pg.reload();pg.wait_for_timeout(800)
  check('被抓後趁死亡卡出現前重新整理，替身照燒',('替身剩 1' in pg.inner_text('#m-start-sub')),pg.inner_text('#m-start-sub'))
  pg.click('#m-start');pg.wait_for_timeout(300);pg.click('#ncgo');pg.wait_for_timeout(300)
  pg.evaluate("(()=>{KT.manual=true;KT.endGame('escape')})()");pg.wait_for_timeout(1300)
  check('一個人都沒帶回來：這夜不算數、燒替身',('再來一次頭一夜' in pg.inner_text('#again')) and pg.evaluate("KT.RUN.lives")==0 and pg.evaluate("KT.RUN.nights.length")==0,[pg.inner_text('#again'),pg.evaluate("KT.RUN.lives")])
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
  pg.evaluate("(()=>{KT.manual=true;const G=KT.G,sv=G.humans.filter(h=>!h.isPlayer);sv[0].saved=true;G.saved=1;G.t=G.night;KT.step(1)})()");pg.wait_for_timeout(1300)
  r=pg.evaluate("KT.RUN.nights[0]")
  check('天亮時還活著的人只算撐到天亮，不算救出',r and r['saved']==1 and r['dawn']>=1 and not r['lost'],r)
  pg.keyboard.press('KeyR');pg.wait_for_timeout(300)
  pg.evaluate("KT.toTitle()");pg.wait_for_timeout(300)
  check('標題寫天亮了要挑祝福','祝福' in pg.inner_text('#m-start-sub'),pg.inner_text('#m-start-sub'))
  am=pg.evaluate("(()=>{const m=MODS.find(x=>x.id===JSON.parse(localStorage.getItem('kaidan-run')).mod);return [m.name,document.querySelector('#almanac').textContent]})()")
